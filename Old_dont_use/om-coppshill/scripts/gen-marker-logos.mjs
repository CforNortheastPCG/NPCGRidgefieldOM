/* ═══════════════════ MARKER BRAND LOGOS ═══════════════════
   Automatically fetches brand logos for the recognizable chains/agencies among
   the aerial markers (Walgreens, Dunkin', Stop & Shop, banks, the transit
   agency, …) and skips small local places that have no real logo.

   Source: Clearbit Logo API (logo.clearbit.com/<domain>), with a Google favicon
   fallback. Saves PNGs to public/logos/markers/ and writes src/markerLogos.js
   mapping each marker `name` → its logo path. FullBleed attaches them by name.

   Run:  npm run logos
   (No API key needed. Re-run any time you add brand markers.)

   To reuse on another deal: edit BRANDS below (match substring → domain) and the
   NAMES list source. Local mom-and-pop names simply won't match and stay bare. */
import { writeFileSync, mkdirSync } from 'node:fs'
import { AERIAL_MARKERS } from '../src/aerialMarkers.js'

/* brand matcher (lowercase substring of the marker name) → website domain(s).
   List several domains when a brand has redirects/sub-brands; we try each. */
const BRANDS = [
  { match: 'walgreens', domains: ['walgreens.com'] },
  { match: 'dunkin', domains: ['dunkindonuts.com', 'dunkin.com'] },
  { match: 'stop & shop', domains: ['stopandshop.com'] },
  { match: 'webster bank', domains: ['websterbank.com'] },
  { match: 'thomaston savings', domains: ['thomastonsavingsbank.com'] },
  { match: 'napa', domains: ['napaonline.com', 'napa.com'] },
  { match: 'bus stop', domains: ['cttransit.com'] },   // transit agency (CTtransit)
  // small local places (diners, nail salons, the library, etc.) intentionally omitted
]

/* Marker names to resolve: the canonical list plus any combined/renamed ones. */
const NAMES = [
  ...new Set([
    ...AERIAL_MARKERS.map((m) => m.name),
    'Bus Stop — South Main St',   // combined NB/SB transit pin used on bleed-2
  ]),
]

const root = new URL('../', import.meta.url)
const outDir = new URL('public/logos/markers/', root)
mkdirSync(outDir, { recursive: true })

const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')

async function download(url) {
  try {
    const res = await fetch(url, { redirect: 'follow' })
    if (!res.ok) return null
    const buf = Buffer.from(await res.arrayBuffer())
    return buf.length > 200 ? buf : null   // guard against 1x1 placeholder pixels
  } catch {
    return null
  }
}

// Try Clearbit (real logo) across all domains first, then Google favicon.
async function fetchLogo(domains) {
  for (const d of domains) {
    const buf = await download(`https://logo.clearbit.com/${d}?size=256&format=png`)
    if (buf) return { buf, domain: d, src: 'clearbit' }
  }
  for (const d of domains) {
    const buf = await download(`https://www.google.com/s2/favicons?domain=${d}&sz=256`)
    if (buf) return { buf, domain: d, src: 'favicon' }
  }
  return null
}

const map = {}
for (const name of NAMES) {
  const brand = BRANDS.find((b) => name.toLowerCase().includes(b.match))
  if (!brand) continue
  const got = await fetchLogo(brand.domains)
  if (!got) { console.warn(`  ✗ no logo for ${name} (${brand.domains.join(', ')})`); continue }
  const file = `${slug(got.domain)}.png`
  writeFileSync(new URL(file, outDir), got.buf)
  map[name] = `/logos/markers/${file}`
  console.log(`  ✓ ${name} → ${file} (${got.src})`)
}

const out = `/* AUTO-GENERATED by scripts/gen-marker-logos.mjs — do not edit by hand.
   Maps a marker \`name\` to a downloaded brand-logo path under /public/logos/markers/. */
export const MARKER_LOGOS = ${JSON.stringify(map, null, 2)}
`
writeFileSync(new URL('src/markerLogos.js', root), out)
console.log(`Wrote src/markerLogos.js (${Object.keys(map).length} logos)`)

/* Drive-time ring generator — COASTAL "raw road-following polygon" method.

   Longwater Corporate Center is on Boston's South Shore, on the water. The
   radial-envelope method (used inland) interpolates a radius straight across
   Massachusetts Bay, ballooning the bands out over the ocean and up the coast
   (Salem reachable in an hour — it isn't). So this uses Valhalla's RAW isochrone
   polygon directly: because `costing: auto` only follows roads, the polygon
   already EXCLUDES the water. We take the outer ring, decimate to even spacing,
   and Chaikin-smooth — no bearing bins, no radial clamp. Reads jaggier than an
   inland map on purpose: it's tracing real coastal road reach. See
   DRIVE_TIMES_MAP_FINAL.md (Black Rock canonical). One /isochrone call.
   npm run isochrones */
import { writeFileSync } from 'node:fs'

const SUBJECT = { lat: 42.15679, lon: -70.879097 } // Longwater Corporate Center, 120 Longwater Dr, Norwell MA
const CONTOURS = [
  { time: 60, color: '#C0392B' },
  { time: 45, color: '#7D3C98' },
  { time: 30, color: '#2471A3' },
  { time: 15, color: '#229954' },
]
const VALHALLA = 'https://valhalla1.openstreetmap.de/isochrone'
const MIN_SPACING_M = 350   // decimation spacing (m) — larger = simpler/smoother
const SMOOTH_PASSES = 2     // Chaikin corner-rounding passes

const R = 6371, toRad = d => d * Math.PI / 180
function haversineM(lat1, lon1, lat2, lon2) {
  const dLa = toRad(lat2 - lat1), dLo = toRad(lon2 - lon1)
  const s = Math.sin(dLa / 2) ** 2 + Math.cos(toRad(lat1)) * Math.cos(toRad(lat2)) * Math.sin(dLo / 2) ** 2
  return 2 * R * 1000 * Math.asin(Math.sqrt(s))
}
function outerRing(geom) {
  const rings = geom.type === 'Polygon' ? [geom.coordinates[0]] : geom.coordinates.map(p => p[0])
  return rings.sort((a, b) => b.length - a.length)[0]
}
// Keep points at least `minM` apart along the ring — thins thousands of raw
// vertices to an even, smooth spacing without changing the shape.
function decimate(ring, minM) {
  const out = []
  let last = null
  for (const [lng, lat] of ring) {
    if (!last || haversineM(last[1], last[0], lat, lng) >= minM) { out.push([lng, lat]); last = [lng, lat] }
  }
  return out
}
function chaikin(pts, iters) {
  let p = pts
  for (let k = 0; k < iters; k++) {
    const out = []
    for (let i = 0; i < p.length; i++) {
      const a = p[i], b = p[(i + 1) % p.length]
      out.push([a[0] * 0.75 + b[0] * 0.25, a[1] * 0.75 + b[1] * 0.25])
      out.push([a[0] * 0.25 + b[0] * 0.75, a[1] * 0.25 + b[1] * 0.75])
    }
    p = out
  }
  return p
}

const body = { locations: [SUBJECT], costing: 'auto', contours: CONTOURS.map(c => ({ time: c.time })), polygons: true, generalize: 6, denoise: 0.1 }
console.log('Requesting isochrone polygons from Valhalla…')
const res = await fetch(`${VALHALLA}?json=${encodeURIComponent(JSON.stringify(body))}`, { headers: { 'User-Agent': 'npcg-om-longwater/1.0' } })
if (!res.ok) throw new Error(`Valhalla ${res.status} — ${(await res.text()).slice(0, 200)}`)
const gj = await res.json()
const byTime = new Map()
for (const f of gj.features || []) {
  if (f.geometry?.type === 'Polygon' || f.geometry?.type === 'MultiPolygon') byTime.set(f.properties.contour, outerRing(f.geometry))
}

const bands = CONTOURS.map(c => {
  const ring = byTime.get(c.time)
  if (!ring) throw new Error(`No isochrone for ${c.time} min`)
  let raw = decimate(ring, MIN_SPACING_M) // [[lng,lat]…], water already excluded by costing:auto
  if (raw.length > 1 && raw[0][0] === raw.at(-1)[0] && raw[0][1] === raw.at(-1)[1]) raw.pop()
  let pts = chaikin(raw.map(([lng, lat]) => [lat, lng]), SMOOTH_PASSES) // → [[lat,lng]…]
  pts.push(pts[0])
  pts = pts.map(p => p.map(v => +v.toFixed(5)))
  console.log(`  ${c.time} min: ${ring.length} raw → ${pts.length} pts`)
  return { min: c.time, color: c.color, coords: pts }
})

const file = `/* AUTO-GENERATED by scripts/gen-isochrones.mjs (coastal raw-polygon method) —
   do not hand-edit. Road-following drive-time rings from Longwater Corporate
   Center, 120 Longwater Dr, Norwell MA: raw Valhalla isochrone polygons
   (costing auto, so water is excluded), decimated + Chaikin-smoothed, as
   [lat,lng] arrays. Largest contour first. Re-run: npm run isochrones */

export const ISOCHRONES = [
${bands.map(b => `  { min: ${b.min}, color: '${b.color}', coords: ${JSON.stringify(b.coords)} },`).join('\n')}
]
`
writeFileSync(new URL('../src/isochrones.js', import.meta.url), file)
console.log('Wrote src/isochrones.js')
